"""Build assets/depth.png, assets/masks.png and src/pond-data.js from assets/scene.png.

Usage: python tools/make_masks.py <raw_depth.png> [overlay_out_dir]
  raw_depth.png comes from tools/make_depth.mjs (Depth Anything V2 Small, white = near).
masks.png channels: R = open water (lily pads and rocks removed), G = foliage allowed to sway,
B = warm lights. All shapes below are hand-traced in source pixels (1408x768).
"""
import sys, json
import numpy as np
from PIL import Image, ImageDraw, ImageFilter
from scipy import ndimage as ndi

W, H = 1408, 768
scene = Image.open('assets/scene.png').convert('RGB')
assert scene.size == (W, H)
rgb = np.asarray(scene).astype(np.float32) / 255
hsv = np.asarray(scene.convert('HSV')).astype(np.float32) / 255

POND = [(470,512),(560,506),(640,506),(700,512),(735,520),(785,530),(840,537),(900,545),(950,547),
        (1000,550),(1060,555),(1085,566),(1070,590),(1095,600),(1100,625),(1120,640),(1110,660),
        (1065,662),(1055,671),(1010,667),(960,671),(935,685),(922,708),(905,728),(870,722),(790,722),(745,712),
        (700,712),(625,705),(600,690),(520,688),(480,690),(468,655),(445,618),(400,612),(396,596),
        (428,550),(452,532),(465,518)]
PADS = [
    [(398,568),(450,562),(500,570),(537,580),(532,594),(495,606),(430,604),(395,592)],
    [(470,656),(500,645),(556,644),(562,655),(600,654),(607,668),(592,681),(572,691),(478,691)],
    [(878,537),(1012,540),(1017,560),(992,573),(958,569),(888,553)],
    [(856,700),(896,697),(907,726),(860,723)],
]
HOUSE = [(590,130),(1210,130),(1210,420),(590,420)]
LIGHTS = [(705,280),(1165,280),(1165,356),(705,356)]
BRIDGE = [(985,498),(1270,520),(1270,565),(1000,560)]

def poly_mask(points):
    m = Image.new('L', (W, H), 0)
    ImageDraw.Draw(m).polygon(points, fill=255)
    return np.asarray(m).astype(np.float32) / 255

def blur(a, r):
    return ndi.gaussian_filter(a, r)

# --- depth -----------------------------------------------------------------
depth = np.asarray(Image.open(sys.argv[1]).convert('L').resize((W, H), Image.BICUBIC)).astype(np.float32) / 255
depth = blur(depth, 1.5)
depth = (depth - depth.min()) / (depth.max() - depth.min())
Image.fromarray((depth * 255).astype(np.uint8)).save('assets/depth.png')

# --- water (R) -------------------------------------------------------------
water = poly_mask(POND)
h, s, v = hsv[..., 0], hsv[..., 1], hsv[..., 2]
# inside the hand-traced pad areas, only actual leaf/flower pixels are removed from the water
leaf = ((h > 0.10) & (h < 0.45) & (s > 0.20) & (v > 0.32)) | ((s > 0.25) & (v > 0.75) & (h < 0.14))
pad_area = np.zeros((H, W), np.float32)
for p in PADS:
    pad_area = np.maximum(pad_area, poly_mask(p))
pads_px = ndi.binary_dilation(ndi.binary_closing(leaf & (pad_area > 0.5), iterations=2), iterations=2)
water *= 1 - pads_px.astype(np.float32)
water = ndi.binary_erosion(water > 0.5, iterations=2).astype(np.float32)
water = blur(water, 2.0)

# --- sway (G) --------------------------------------------------------------
green = ((h > 0.12) & (h < 0.47) & (s > 0.22) & (v > 0.12)).astype(np.float32)
flower = ((s > 0.35) & (v > 0.55) & ((h < 0.08) | (h > 0.55))).astype(np.float32)
veg = np.clip(green + flower * (depth > 0.45), 0, 1)
veg = ndi.binary_opening(veg > 0, iterations=1).astype(np.float32)
near = np.clip((depth - 0.16) / 0.5, 0, 1)            # distant forest barely moves
sway = veg * (0.25 + 0.75 * near)
sway *= 1 - np.clip(poly_mask(POND) + poly_mask(HOUSE) + poly_mask(BRIDGE), 0, 1)
ys = np.linspace(0, 1, H)[:, None]
sway *= np.clip((ys - 0.18) / 0.2, 0, 1)                # keep the sky and pine crowns still
sway = blur(sway, 5.0)
sway = np.clip(sway * 1.25, 0, 1)

# --- lights (B) ------------------------------------------------------------
r, g, b = rgb[..., 0], rgb[..., 1], rgb[..., 2]
warm = ((r > 0.88) & (g > 0.66) & (r - b > 0.22)).astype(np.float32) * poly_mask(LIGHTS)
light = np.clip(blur(ndi.binary_dilation(warm > 0, iterations=2).astype(np.float32), 5.0) * 1.6, 0, 1)

masks = np.stack([water, sway, light], -1)
Image.fromarray((np.clip(masks, 0, 1) * 255).astype(np.uint8)).save('assets/masks.png')

# --- pond data -------------------------------------------------------------
poly = [[round(x / W, 5), round(y / H, 5)] for x, y in POND]
pads = []
for p in PADS:
    xs = [q[0] for q in p]; ysp = [q[1] for q in p]
    pads.append({'u': round(sum(xs) / len(xs) / W, 5), 'v': round(sum(ysp) / len(ysp) / H, 5),
                 'r': round((max(xs) - min(xs)) / 2 / W, 5)})
with open('src/pond-data.js', 'w', encoding='utf-8') as f:
    f.write('// Generated by tools/make_masks.py. Do not edit by hand.\n')
    f.write('export const POND_POLYGON = ' + json.dumps(poly) + ';\n')
    f.write('export const OBSTACLES = ' + json.dumps(pads) + ';\n')

# --- overlays for eyeballing ------------------------------------------------
if len(sys.argv) > 2:
    out = sys.argv[2]
    for i, (name, col) in enumerate([('water', (255, 0, 80)), ('sway', (255, 230, 0)), ('light', (0, 200, 255))]):
        a = masks[..., i:i + 1]
        o = rgb * (1 - 0.6 * a) + np.array(col, np.float32) / 255 * 0.6 * a
        Image.fromarray((o * 255).astype(np.uint8)).save(f'{out}/overlay_{name}.png')
print('ok')
